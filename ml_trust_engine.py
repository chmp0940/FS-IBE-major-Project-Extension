"""
ML Trust Engine — Machine Learning-based behavioral trust scoring for IoT queries.

Implements a multi-model approach with 6 classifiers:
  1. Isolation Forest (unsupervised) — catches novel/unknown attack patterns
  2. Random Forest (supervised) — high accuracy on known attack types
  3. SVM (supervised) — kernel-based margin classifier
  4. KNN (supervised) — instance-based distance classifier
  5. Decision Tree (supervised) — interpretable tree-based classifier
  6. MLP (supervised) — neural network deep learning classifier

The engine provides:
  - Training from synthetic attack data (generated by attack_simulator.py)
  - Real-time evaluation: given a feature vector, returns (is_anomaly, confidence, anomaly_score)
  - Model persistence (save/load via joblib)
  - Per-model performance metrics for comparative analysis

Features (8 total):
  1. query_frequency        — queries per minute from this user
  2. epoch_mismatch_rate    — fraction of queries with wrong epoch
  3. sig_failure_rate       — rolling signature failure rate
  4. inter_query_interval   — avg seconds between consecutive queries
  5. payload_size_deviation — std dev of query payload sizes
  6. time_of_day_sin        — sine-encoded hour
  7. time_of_day_cos        — cosine-encoded hour
  8. query_burst_count      — queries within 1-second windows
"""

import os
import tempfile
import numpy as np
import warnings

from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.svm import SVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.tree import DecisionTreeClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
)

try:
    import joblib
    HAS_JOBLIB = True
except ImportError:
    HAS_JOBLIB = False

# Feature names (must match attack_simulator.py and FeatureExtractor)
FEATURE_NAMES = [
    "query_frequency",
    "epoch_mismatch_rate",
    "sig_failure_rate",
    "inter_query_interval",
    "payload_size_deviation",
    "time_of_day_sin",
    "time_of_day_cos",
    "query_burst_count",
]

# Ordered list of supervised model names for iteration
SUPERVISED_MODEL_NAMES = [
    "random_forest",
    "svm",
    "knn",
    "decision_tree",
    "mlp",
]


class MLTrustEngine:
    """
    Multi-model ML engine for behavioral trust scoring.

    Uses Isolation Forest (unsupervised anomaly detection) combined with
    five supervised classifiers (Random Forest, SVM, KNN, Decision Tree, MLP)
    via weighted majority voting.

    The final decision combines all models:
      - Each supervised model votes with its prediction probability
      - Isolation Forest provides an anomaly signal
      - Weighted majority voting determines the final classification
    """

    def __init__(self, contamination=0.15, n_estimators_iso=100, n_estimators_rf=100,
                 random_state=42, n_jobs=-1):
        """
        Args:
            contamination: Expected proportion of anomalies (for Isolation Forest)
            n_estimators_iso: Number of trees in Isolation Forest
            n_estimators_rf: Number of trees in Random Forest
            random_state: Random seed for reproducibility
            n_jobs: Number of parallel workers used by the forest models
        """
        self.contamination = contamination
        self.random_state = random_state

        # --- Model 1: Isolation Forest (unsupervised — detects novel anomalies) ---
        self.isolation_forest = IsolationForest(
            n_estimators=n_estimators_iso,
            contamination=contamination,
            random_state=random_state,
            n_jobs=n_jobs,
        )

        # --- Model 2: Random Forest (supervised — ensemble tree classifier) ---
        self.random_forest = RandomForestClassifier(
            n_estimators=n_estimators_rf,
            max_depth=10,
            min_samples_split=5,
            random_state=random_state,
            n_jobs=n_jobs,
        )

        # --- Model 3: SVM (supervised — kernel-based margin classifier) ---
        self.svm = SVC(
            kernel='rbf',
            C=1.0,
            gamma='scale',
            probability=True,
            random_state=random_state,
        )

        # --- Model 4: KNN (supervised — instance-based distance classifier) ---
        self.knn = KNeighborsClassifier(
            n_neighbors=5,
            weights='distance',
            metric='minkowski',
            n_jobs=n_jobs,
        )

        # --- Model 5: Decision Tree (supervised — interpretable tree classifier) ---
        self.decision_tree = DecisionTreeClassifier(
            max_depth=10,
            min_samples_split=5,
            criterion='gini',
            random_state=random_state,
        )

        # --- Model 6: MLP (supervised — neural network classifier) ---
        self.mlp = MLPClassifier(
            hidden_layer_sizes=(64, 32),
            activation='relu',
            solver='adam',
            max_iter=500,
            early_stopping=True,
            validation_fraction=0.1,
            random_state=random_state,
        )

        # Feature scaler
        self.scaler = StandardScaler()

        # Model state
        self.is_trained = False
        self.training_metrics = {}

    def _get_supervised_models(self):
        """Return ordered dict of supervised model name → model object."""
        return {
            "random_forest": self.random_forest,
            "svm": self.svm,
            "knn": self.knn,
            "decision_tree": self.decision_tree,
            "mlp": self.mlp,
        }

    def train(self, X, y, test_size=0.2, verbose=True):
        """
        Train all 6 models on the provided dataset.

        Args:
            X: Feature matrix (n_samples, 8)
            y: Labels (0=normal, 1=malicious)
            test_size: Fraction held out for testing
            verbose: Print training results
        """
        if verbose:
            print("\n" + "=" * 60, flush=True)
            print("  ML Trust Engine — Training (6 Models)", flush=True)
            print("=" * 60, flush=True)

        # Split data
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=test_size, random_state=self.random_state, stratify=y
        )

        if verbose:
            print(f"  Training samples: {len(X_train)}", flush=True)
            print(f"  Test samples: {len(X_test)}", flush=True)
            print(f"  Features: {X.shape[1]}", flush=True)

        # Scale features
        X_train_scaled = self.scaler.fit_transform(X_train)
        X_test_scaled = self.scaler.transform(X_test)

        # ===== Train Isolation Forest (unsupervised — uses only normal data) =====
        if verbose:
            print("\n  [1/6] Training Isolation Forest (unsupervised)...", flush=True)
        X_train_normal = X_train_scaled[y_train == 0]
        self.isolation_forest.fit(X_train_normal)

        # Evaluate Isolation Forest
        iso_pred = self.isolation_forest.predict(X_test_scaled)
        # IF returns: 1 = normal, -1 = anomaly → convert to 0/1
        iso_pred_binary = (iso_pred == -1).astype(int)
        iso_scores = -self.isolation_forest.score_samples(X_test_scaled)  # Higher = more anomalous

        iso_acc = accuracy_score(y_test, iso_pred_binary)
        iso_prec = precision_score(y_test, iso_pred_binary, zero_division=0)
        iso_rec = recall_score(y_test, iso_pred_binary, zero_division=0)
        iso_f1 = f1_score(y_test, iso_pred_binary, zero_division=0)

        if verbose:
            print(f"  Isolation Forest — Acc: {iso_acc:.4f}, Prec: {iso_prec:.4f}, "
                  f"Rec: {iso_rec:.4f}, F1: {iso_f1:.4f}", flush=True)

        self.training_metrics = {
            "iso_accuracy": iso_acc,
            "iso_precision": iso_prec,
            "iso_recall": iso_rec,
            "iso_f1": iso_f1,
        }

        # ===== Train all supervised models =====
        supervised_models = self._get_supervised_models()
        model_display_names = {
            "random_forest": "Random Forest",
            "svm": "SVM",
            "knn": "KNN",
            "decision_tree": "Decision Tree",
            "mlp": "MLP (Neural Network)",
        }

        supervised_preds = {}
        supervised_probas = {}

        for idx, (name, model) in enumerate(supervised_models.items(), start=2):
            if verbose:
                print(f"\n  [{idx}/6] Training {model_display_names[name]}...", flush=True)

            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                model.fit(X_train_scaled, y_train)

            pred = model.predict(X_test_scaled)
            proba = model.predict_proba(X_test_scaled)[:, 1]

            supervised_preds[name] = pred
            supervised_probas[name] = proba

            m_acc = accuracy_score(y_test, pred)
            m_prec = precision_score(y_test, pred, zero_division=0)
            m_rec = recall_score(y_test, pred, zero_division=0)
            m_f1 = f1_score(y_test, pred, zero_division=0)

            self.training_metrics[f"{name}_accuracy"] = m_acc
            self.training_metrics[f"{name}_precision"] = m_prec
            self.training_metrics[f"{name}_recall"] = m_rec
            self.training_metrics[f"{name}_f1"] = m_f1

            if verbose:
                print(f"  {model_display_names[name]} — Acc: {m_acc:.4f}, Prec: {m_prec:.4f}, "
                      f"Rec: {m_rec:.4f}, F1: {m_f1:.4f}", flush=True)

        # ===== Combined evaluation (weighted majority voting) =====
        combined_pred = self._combine_predictions_multi(
            iso_pred_binary, iso_scores, supervised_preds, supervised_probas
        )

        combined_acc = accuracy_score(y_test, combined_pred)
        combined_prec = precision_score(y_test, combined_pred, zero_division=0)
        combined_rec = recall_score(y_test, combined_pred, zero_division=0)
        combined_f1 = f1_score(y_test, combined_pred, zero_division=0)

        self.training_metrics["combined_accuracy"] = combined_acc
        self.training_metrics["combined_precision"] = combined_prec
        self.training_metrics["combined_recall"] = combined_rec
        self.training_metrics["combined_f1"] = combined_f1

        if verbose:
            print(f"\n  {'=' * 50}", flush=True)
            print(f"  === Combined Ensemble Performance (6 Models) ===", flush=True)
            print(f"  {'=' * 50}", flush=True)
            print(f"  Accuracy:  {combined_acc:.4f}", flush=True)
            print(f"  Precision: {combined_prec:.4f}", flush=True)
            print(f"  Recall:    {combined_rec:.4f}", flush=True)
            print(f"  F1 Score:  {combined_f1:.4f}", flush=True)

            print(f"\n  Confusion Matrix (Combined Ensemble):", flush=True)
            cm = confusion_matrix(y_test, combined_pred)
            print(f"    TN={cm[0][0]:4d}  FP={cm[0][1]:4d}", flush=True)
            print(f"    FN={cm[1][0]:4d}  TP={cm[1][1]:4d}", flush=True)

            # Feature importance (from Random Forest)
            print(f"\n  Feature Importance (Random Forest):", flush=True)
            importances = self.random_forest.feature_importances_
            sorted_idx = np.argsort(importances)[::-1]
            for idx in sorted_idx:
                print(f"    {FEATURE_NAMES[idx]:30s}: {importances[idx]:.4f}", flush=True)

            # Per-model summary table
            print(f"\n  {'=' * 65}", flush=True)
            print(f"  {'Model':<22} {'Accuracy':>10} {'Precision':>10} {'Recall':>10} {'F1':>10}", flush=True)
            print(f"  {'-' * 62}", flush=True)
            print(f"  {'Isolation Forest':<22} {iso_acc:>10.4f} {iso_prec:>10.4f} {iso_rec:>10.4f} {iso_f1:>10.4f}", flush=True)
            for name in SUPERVISED_MODEL_NAMES:
                dname = model_display_names[name]
                a = self.training_metrics[f"{name}_accuracy"]
                p = self.training_metrics[f"{name}_precision"]
                r = self.training_metrics[f"{name}_recall"]
                f = self.training_metrics[f"{name}_f1"]
                print(f"  {dname:<22} {a:>10.4f} {p:>10.4f} {r:>10.4f} {f:>10.4f}", flush=True)
            print(f"  {'-' * 62}", flush=True)
            print(f"  {'Combined Ensemble':<22} {combined_acc:>10.4f} {combined_prec:>10.4f} {combined_rec:>10.4f} {combined_f1:>10.4f}", flush=True)
            print("=" * 60, flush=True)

        self.is_trained = True
        return self.training_metrics

    def _combine_predictions_multi(self, iso_pred, iso_scores, supervised_preds, supervised_probas):
        """
        Combine Isolation Forest and all supervised model predictions
        using weighted majority voting.

        Strategy:
          - Compute weighted average probability from all supervised models
          - If weighted avg > 0.6 → malicious (high confidence from supervised ensemble)
          - If weighted avg > 0.4 AND Isolation Forest agrees → malicious
          - Otherwise → normal
        """
        n_samples = len(iso_pred)
        combined = np.zeros(n_samples, dtype=int)

        # Stack all supervised probabilities: shape (n_models, n_samples)
        proba_stack = np.array([supervised_probas[name] for name in SUPERVISED_MODEL_NAMES])

        # Weighted average: each model weighted equally (could be tuned)
        avg_proba = proba_stack.mean(axis=0)

        for i in range(n_samples):
            if avg_proba[i] > 0.6:
                # Strong supervised consensus → malicious
                combined[i] = 1
            elif avg_proba[i] > 0.4 and iso_pred[i] == 1:
                # Moderate suspicion + IF anomaly → malicious
                combined[i] = 1
            else:
                combined[i] = 0

        return combined

    def _combine_predictions(self, iso_pred, rf_pred, iso_scores, rf_proba):
        """
        Legacy method: Combine Isolation Forest and Random Forest predictions.
        Kept for backward compatibility but internally routes to multi-model
        combination when all models are trained.

        Strategy:
          - If RF says malicious with high confidence (>0.6) → malicious
          - If both models agree on malicious → malicious
          - If IF says anomaly but RF says normal → use RF (fewer false positives)
          - Otherwise → normal
        """
        combined = np.zeros(len(iso_pred), dtype=int)
        for i in range(len(iso_pred)):
            if rf_proba[i] > 0.6:
                combined[i] = 1
            elif iso_pred[i] == 1 and rf_pred[i] == 1:
                combined[i] = 1
            else:
                combined[i] = 0
        return combined

    def evaluate(self, features_dict):
        """
        Evaluate a single query's features and return trust decision.

        Uses all 6 models via weighted majority voting for robust decisions.

        Args:
            features_dict: Dict with 8 feature keys (from FeatureExtractor)

        Returns:
            tuple: (is_anomaly: bool, confidence: float, anomaly_score: float)
              - is_anomaly: True if query is flagged as suspicious
              - confidence: 0.0–1.0, how confident the models are
              - anomaly_score: raw anomaly score (higher = more anomalous)
        """
        if not self.is_trained:
            return False, 0.0, 0.0

        # Convert dict to feature vector
        feature_vec = np.array([[features_dict[f] for f in FEATURE_NAMES]])

        # Scale
        feature_scaled = self.scaler.transform(feature_vec)

        # --- Isolation Forest ---
        iso_pred = self.isolation_forest.predict(feature_scaled)[0]
        iso_score = -self.isolation_forest.score_samples(feature_scaled)[0]
        iso_is_anomaly = (iso_pred == -1)

        # --- All supervised models ---
        supervised_probas = []
        supervised_models = self._get_supervised_models()
        for name, model in supervised_models.items():
            proba = model.predict_proba(feature_scaled)[0][1]
            supervised_probas.append(proba)

        # Weighted average probability across all supervised models
        avg_proba = np.mean(supervised_probas)

        # Combined decision via weighted majority voting
        if avg_proba > 0.6:
            is_anomaly = True
            confidence = avg_proba
        elif avg_proba > 0.4 and iso_is_anomaly:
            is_anomaly = True
            confidence = (iso_score + avg_proba) / 2.0
        else:
            is_anomaly = False
            confidence = 1.0 - avg_proba

        anomaly_score = (iso_score * 0.3 + avg_proba * 0.7)

        return is_anomaly, min(confidence, 1.0), anomaly_score

    def save_models(self, directory="models"):
        """Save all trained models to disk."""
        if not self.is_trained:
            print("  Warning: Models not trained, nothing to save.", flush=True)
            return

        directory = os.path.abspath(directory)
        os.makedirs(directory, exist_ok=True)

        if HAS_JOBLIB:
            artifacts = {
                "isolation_forest.joblib": self.isolation_forest,
                "random_forest.joblib": self.random_forest,
                "svm.joblib": self.svm,
                "knn.joblib": self.knn,
                "decision_tree.joblib": self.decision_tree,
                "mlp.joblib": self.mlp,
                "scaler.joblib": self.scaler,
                "training_metrics.joblib": self.training_metrics,
            }
            for filename, value in artifacts.items():
                target = os.path.join(directory, filename)
                # Write to a fresh file first. This avoids leaving a truncated
                # model if a notebook rerun is interrupted while overwriting it.
                fd, temporary = tempfile.mkstemp(
                    prefix=f".{filename}.", suffix=".tmp", dir=directory
                )
                os.close(fd)
                try:
                    joblib.dump(value, temporary)
                    os.replace(temporary, target)
                except OSError as exc:
                    if os.path.exists(temporary):
                        os.remove(temporary)
                    raise OSError(
                        f"Could not save model artifact '{target}'. "
                        "Close any process that is using the models folder and retry."
                    ) from exc
            print(f"  Models saved to {directory}/ (6 models + scaler + metrics)", flush=True)
        else:
            print("  Warning: joblib not available, models not saved.", flush=True)

    def load_models(self, directory="models"):
        """Load all trained models from disk."""
        if not HAS_JOBLIB:
            print("  Warning: joblib not available, cannot load models.", flush=True)
            return False

        try:
            self.isolation_forest = joblib.load(os.path.join(directory, "isolation_forest.joblib"))
            self.random_forest = joblib.load(os.path.join(directory, "random_forest.joblib"))
            self.svm = joblib.load(os.path.join(directory, "svm.joblib"))
            self.knn = joblib.load(os.path.join(directory, "knn.joblib"))
            self.decision_tree = joblib.load(os.path.join(directory, "decision_tree.joblib"))
            self.mlp = joblib.load(os.path.join(directory, "mlp.joblib"))
            self.scaler = joblib.load(os.path.join(directory, "scaler.joblib"))
            self.training_metrics = joblib.load(os.path.join(directory, "training_metrics.joblib"))
            self.is_trained = True
            print(f"  Models loaded from {directory}/ (6 models)", flush=True)
            return True
        except FileNotFoundError:
            print(f"  Warning: Model files not found in {directory}/", flush=True)
            return False


def train_from_dataset(data_path="training_data.csv", save_dir="models", verbose=True):
    """
    Convenience function: load dataset, train all 6 models, save to disk.
    Returns the trained MLTrustEngine instance.
    """
    from attack_simulator import load_dataset

    X, y, attack_types = load_dataset(data_path)

    engine = MLTrustEngine()
    engine.train(X, y, verbose=verbose)
    engine.save_models(save_dir)

    return engine


