"""
ML Trust Engine — Machine Learning-based behavioral trust scoring for IoT queries.

Implements a six-model ensemble:
  1. Isolation Forest (unsupervised) — catches novel/unknown attack patterns
  2. Random Forest, SVM, KNN, Decision Tree, and MLP (supervised)

The engine provides:
  - Training from synthetic attack data (generated by attack_simulator.py)
  - Real-time evaluation: given a feature vector, returns (is_anomaly, confidence, anomaly_score)
  - Model persistence (save/load via joblib)

Features (8 total):
  1. query_frequency        — queries per minute from this user
  2. epoch_mismatch_rate    — fraction of queries with wrong epoch
  3. sig_failure_rate       — rolling signature failure rate
  4. inter_query_interval   — avg seconds between consecutive queries
  5. payload_size_deviation — std dev of query payload sizes
  6. time_of_day_sin        — sine-encoded hour
  7. time_of_day_cos        — cosine-encoded hour
  8. query_burst_count      — queries within 1-second windows
"""

import os
import numpy as np
import warnings

from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.svm import SVC
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
)

try:
    import joblib
    HAS_JOBLIB = True
except ImportError:
    HAS_JOBLIB = False

# Feature names (must match attack_simulator.py and FeatureExtractor)
FEATURE_NAMES = [
    "query_frequency",
    "epoch_mismatch_rate",
    "sig_failure_rate",
    "inter_query_interval",
    "payload_size_deviation",
    "time_of_day_sin",
    "time_of_day_cos",
    "query_burst_count",
]

SUPERVISED_MODEL_NAMES = (
    "random_forest",
    "svm",
    "knn",
    "decision_tree",
    "mlp",
)


class MLTrustEngine:
    """
    Six-model ensemble for behavioral trust scoring.

    Isolation Forest contributes an unsupervised anomaly vote. Five supervised
    classifiers contribute weighted probabilities and votes to the final result.
    """

    def __init__(self, contamination=0.15, n_estimators_iso=100, n_estimators_rf=100,
                 random_state=42):
        """
        Args:
            contamination: Expected proportion of anomalies (for Isolation Forest)
            n_estimators_iso: Number of trees in Isolation Forest
            n_estimators_rf: Number of trees in Random Forest
            random_state: Random seed for reproducibility
        """
        self.contamination = contamination
        self.random_state = random_state

        # Unsupervised model — detects novel anomalies without labels
        self.isolation_forest = IsolationForest(
            n_estimators=n_estimators_iso,
            contamination=contamination,
            random_state=random_state,
            n_jobs=-1,
        )

        # Supervised model — classifies known attack patterns
        self.random_forest = RandomForestClassifier(
            n_estimators=n_estimators_rf,
            max_depth=10,
            min_samples_split=5,
            random_state=random_state,
            n_jobs=1,
        )
        self.svm = SVC(
            kernel="linear",
            probability=True,
            random_state=random_state,
        )
        self.knn = KNeighborsClassifier(n_neighbors=5, n_jobs=1)
        self.decision_tree = DecisionTreeClassifier(
            max_depth=12,
            min_samples_leaf=2,
            random_state=random_state,
        )
        self.mlp = MLPClassifier(
            hidden_layer_sizes=(64,),
            max_iter=200,
            early_stopping=True,
            n_iter_no_change=10,
            random_state=random_state,
        )

        # Feature scaler
        self.scaler = StandardScaler()

        # Model state
        self.is_trained = False
        self.training_metrics = {}

    def train(self, X, y, test_size=0.2, verbose=True):
        """
        Train the Isolation Forest and five supervised models on the dataset.

        Args:
            X: Feature matrix (n_samples, 8)
            y: Labels (0=normal, 1=malicious)
            test_size: Fraction held out for testing
            verbose: Print training results
        """
        if verbose:
            print("\n" + "=" * 60, flush=True)
            print("  ML Trust Engine — Training", flush=True)
            print("=" * 60, flush=True)

        # Split data
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=test_size, random_state=self.random_state, stratify=y
        )

        if verbose:
            print(f"  Training samples: {len(X_train)}", flush=True)
            print(f"  Test samples: {len(X_test)}", flush=True)
            print(f"  Features: {X.shape[1]}", flush=True)

        # Scale features
        X_train_scaled = self.scaler.fit_transform(X_train)
        X_test_scaled = self.scaler.transform(X_test)

        # --- Train Isolation Forest (unsupervised — uses only normal data) ---
        if verbose:
            print("\n  Training Isolation Forest (unsupervised)...", flush=True)
        X_train_normal = X_train_scaled[y_train == 0]
        self.isolation_forest.fit(X_train_normal)

        supervised_models = {
            "random_forest": self.random_forest,
            "svm": self.svm,
            "knn": self.knn,
            "decision_tree": self.decision_tree,
            "mlp": self.mlp,
        }
        supervised_predictions = {}
        supervised_probabilities = {}
        for name, model in supervised_models.items():
            if verbose:
                print(f"\n  Training {name.replace('_', ' ').title()}...", flush=True)
            model.fit(X_train_scaled, y_train)
            supervised_predictions[name] = model.predict(X_test_scaled)
            supervised_probabilities[name] = model.predict_proba(X_test_scaled)[:, 1]

        # Isolation Forest returns 1 for normal and -1 for anomaly.
        iso_predictions = (self.isolation_forest.predict(X_test_scaled) == -1).astype(int)
        iso_scores = -self.isolation_forest.score_samples(X_test_scaled)
        combined_predictions = self._combine_predictions_multi(
            iso_predictions, iso_scores, supervised_predictions, supervised_probabilities
        )

        self.training_metrics = {}
        model_predictions = {"iso": iso_predictions}
        model_predictions.update({
            "random_forest": supervised_predictions["random_forest"],
            "svm": supervised_predictions["svm"],
            "knn": supervised_predictions["knn"],
            "decision_tree": supervised_predictions["decision_tree"],
            "mlp": supervised_predictions["mlp"],
            "combined": combined_predictions,
        })
        for name, predictions in model_predictions.items():
            self.training_metrics.update({
                f"{name}_accuracy": accuracy_score(y_test, predictions),
                f"{name}_precision": precision_score(y_test, predictions, zero_division=0),
                f"{name}_recall": recall_score(y_test, predictions, zero_division=0),
                f"{name}_f1": f1_score(y_test, predictions, zero_division=0),
            })

        if verbose:
            print("\n  === Six-Model Ensemble Performance ===", flush=True)
            for name in ("iso", *SUPERVISED_MODEL_NAMES, "combined"):
                print(
                    f"  {name.replace('_', ' ').title():<18} "
                    f"Accuracy: {self.training_metrics[f'{name}_accuracy']:.4f} "
                    f"F1: {self.training_metrics[f'{name}_f1']:.4f}",
                    flush=True,
                )

            print("\n  Combined Confusion Matrix:", flush=True)
            cm = confusion_matrix(y_test, combined_predictions)
            print(f"    TN={cm[0][0]:4d}  FP={cm[0][1]:4d}", flush=True)
            print(f"    FN={cm[1][0]:4d}  TP={cm[1][1]:4d}", flush=True)

            # Feature importance (from Random Forest)
            print(f"\n  Feature Importance (Random Forest):", flush=True)
            importances = self.random_forest.feature_importances_
            sorted_idx = np.argsort(importances)[::-1]
            for idx in sorted_idx:
                print(f"    {FEATURE_NAMES[idx]:30s}: {importances[idx]:.4f}", flush=True)

            print("=" * 60, flush=True)

        self.is_trained = True
        return self.training_metrics

    @staticmethod
    def _combine_predictions_multi(iso_pred, iso_scores, supervised_preds, supervised_probas):
        """Combine five supervised weighted votes with the Isolation Forest vote."""
        weights = {
            "random_forest": 0.25,
            "svm": 0.20,
            "knn": 0.15,
            "decision_tree": 0.15,
            "mlp": 0.25,
        }
        available = [name for name in SUPERVISED_MODEL_NAMES if name in supervised_preds]
        total_weight = sum(weights[name] for name in available)
        if not available or total_weight == 0:
            raise ValueError("At least one supervised model is required for ensemble voting")

        weighted_votes = sum(
            weights[name] * np.asarray(supervised_preds[name], dtype=float)
            for name in available
        ) / total_weight
        weighted_probabilities = sum(
            weights[name] * np.asarray(supervised_probas[name], dtype=float)
            for name in available
        ) / total_weight
        supervised_score = 0.5 * weighted_votes + 0.5 * weighted_probabilities
        # A modest unsupervised contribution helps flag novel outliers without
        # allowing Isolation Forest alone to dominate the supervised ensemble.
        ensemble_score = 0.85 * supervised_score + 0.15 * np.asarray(iso_pred, dtype=float)
        return (ensemble_score >= 0.5).astype(int)

    def _combine_predictions(self, iso_pred, rf_pred, iso_scores, rf_proba):
        """Compatibility wrapper for callers using the former two-model API."""
        return self._combine_predictions_multi(
            iso_pred,
            iso_scores,
            {"random_forest": rf_pred},
            {"random_forest": rf_proba},
        )

    def evaluate(self, features_dict):
        """
        Evaluate a single query's features and return trust decision.

        Args:
            features_dict: Dict with 8 feature keys (from FeatureExtractor)

        Returns:
            tuple: (is_anomaly: bool, confidence: float, anomaly_score: float)
              - is_anomaly: True if query is flagged as suspicious
              - confidence: 0.0–1.0, how confident the models are
              - anomaly_score: raw anomaly score (higher = more anomalous)
        """
        if not self.is_trained:
            return False, 0.0, 0.0

        # Convert dict to feature vector
        feature_vec = np.array([[features_dict[f] for f in FEATURE_NAMES]])

        # Scale
        feature_scaled = self.scaler.transform(feature_vec)

        iso_pred = (self.isolation_forest.predict(feature_scaled) == -1).astype(int)
        iso_score = -self.isolation_forest.score_samples(feature_scaled)
        supervised_predictions = {
            name: getattr(self, name).predict(feature_scaled)
            for name in SUPERVISED_MODEL_NAMES
        }
        supervised_probabilities = {
            name: getattr(self, name).predict_proba(feature_scaled)[:, 1]
            for name in SUPERVISED_MODEL_NAMES
        }
        prediction = self._combine_predictions_multi(
            iso_pred, iso_score, supervised_predictions, supervised_probabilities
        )[0]
        confidence = float(np.mean([
            supervised_probabilities[name][0] for name in SUPERVISED_MODEL_NAMES
        ]))
        is_anomaly = bool(prediction)
        if not is_anomaly:
            confidence = 1.0 - confidence
        return is_anomaly, min(max(confidence, 0.0), 1.0), float(iso_score[0])

    def save_models(self, directory="models"):
        """Save trained models to disk."""
        if not self.is_trained:
            print("  Warning: Models not trained, nothing to save.", flush=True)
            return

        os.makedirs(directory, exist_ok=True)

        if HAS_JOBLIB:
            for name in ("isolation_forest", *SUPERVISED_MODEL_NAMES):
                joblib.dump(getattr(self, name), os.path.join(directory, f"{name}.joblib"))
            joblib.dump(self.scaler, os.path.join(directory, "scaler.joblib"))
            joblib.dump(self.training_metrics, os.path.join(directory, "training_metrics.joblib"))
            print(f"  Models saved to {directory}/", flush=True)
        else:
            print("  Warning: joblib not available, models not saved.", flush=True)

    def load_models(self, directory="models"):
        """Load trained models from disk."""
        if not HAS_JOBLIB:
            print("  Warning: joblib not available, cannot load models.", flush=True)
            return False

        try:
            for name in ("isolation_forest", *SUPERVISED_MODEL_NAMES):
                setattr(self, name, joblib.load(os.path.join(directory, f"{name}.joblib")))
            self.scaler = joblib.load(os.path.join(directory, "scaler.joblib"))
            self.training_metrics = joblib.load(os.path.join(directory, "training_metrics.joblib"))
            self.is_trained = True
            print(f"  Models loaded from {directory}/", flush=True)
            return True
        except FileNotFoundError:
            print(f"  Warning: Model files not found in {directory}/", flush=True)
            return False


def train_from_dataset(data_path="training_data.csv", save_dir="models", verbose=True):
    """
    Convenience function: load dataset, train models, save to disk.
    Returns the trained MLTrustEngine instance.
    """
    from attack_simulator import load_dataset

    X, y, attack_types = load_dataset(data_path)

    engine = MLTrustEngine()
    engine.train(X, y, verbose=verbose)
    engine.save_models(save_dir)

    return engine


